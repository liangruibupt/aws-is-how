// 推土机 Bonecrusher —— 履带推土机 → 左臂（整车竖立：履带贴向躯干，车头朝下伸出紫色拳头；推铲翻上成前臂外侧护盾，松土器折起成肩甲尖角）
import * as THREE from 'three';
import { Rig, emblemBadge, basis } from '../kit.js';

export function buildBonecrusher(M) {
  const R = new Rig('bonecrusher', M);
  const S = [-1, 1];

  // ── 底盘（根）：履带、车架、发动机罩、驾驶室 ──
  const C = R.part('chassis', null, [0, 0, 0]);
  for (const s of S) {
    R.track(C, [s * 0.95, 0.45, 0], { L: 3.0, R: 0.45, w: 0.62 });
    R.box(C, [0.66, 0.05, 3.3], [s * 0.95, 0.97, 0], 'paint', { r: 0.02 });
    R.box(C, [0.08, 0.14, 1.5], [s * 1.3, 0.55, 0.9], 'dark', { r: 0.02 });            // 推臂滑轨
  }
  R.box(C, [1.2, 0.5, 2.8], [0, 0.62, 0], 'dark', { r: 0.05 });
  R.box(C, [1.9, 0.3, 3.2], [0, 1.07, -0.1], 'paintDark', { r: 0.04 });
  R.box(C, [0.5, 0.36, 1.0], [0, 0.65, 1.75], 'dark', { r: 0.03 });                    // 拳头滑轨
  // 发动机罩
  R.box(C, [1.5, 0.75, 1.5], [0, 1.575, 0.55], 'paint', { r: 0.08 });
  for (const s of S) for (let i = 0; i < 4; i++) R.box(C, [0.02, 0.05, 0.9], [s * 0.755, 1.4 + i * 0.12, 0.55], 'black', { r: 0 });
  R.box(C, [1.1, 0.5, 0.04], [0, 1.55, 1.31], 'black', { r: 0 });
  for (let i = 0; i < 4; i++) R.box(C, [1.06, 0.03, 0.03], [0, 1.37 + i * 0.12, 1.33], 'chrome', { r: 0 });
  R.cyl(C, 0.07, 0.7, [0.45, 2.2, 0.85], 'chrome');
  R.cyl(C, 0.085, 0.05, [0.45, 2.56, 0.85], 'dark');
  R.cyl(C, 0.1, 0.4, [-0.45, 2.1, 0.9], 'dark');
  R.cyl(C, 0.14, 0.1, [-0.45, 2.33, 0.9], 'steel');
  for (const s of S) R.lamp(C, [s * 0.55, 1.85, 1.32], { r: 0.08, cone: true, len: 7 });
  // 驾驶室 + 防滚架
  R.box(C, [1.6, 1.1, 1.3], [0, 1.75, -0.85], 'paint', { r: 0.08 });
  R.box(C, [1.36, 0.3, 0.04], [0, 2.12, -0.19], 'glass', { r: 0 });
  R.box(C, [1.3, 0.5, 0.04], [0, 1.95, -1.51], 'glass', { r: 0 });
  for (const s of S) {
    R.box(C, [0.04, 0.6, 1.0], [s * 0.805, 1.95, -0.85], 'glass', { r: 0 });
    R.extrude(C, emblemBadge(0.4), 0.02, 'x', [s * 0.805, 1.45, -0.85], 'purple', { bevel: 0.002 });
    for (const z of [-1.55, -0.15]) R.beam(C, [s * 0.85, z < -1 ? 1.2 : 1.95, z], [s * 0.85, 2.36, z], [0.1, 0.1], 'dark');
  }
  R.box(C, [1.8, 0.1, 1.5], [0, 2.4, -0.85], 'dark', { r: 0.03 });
  R.cyl(C, 0.06, 0.08, [0.6, 2.49, -1.3], 'lensA');
  R.box(C, [1.3, 0.5, 0.3], [0, 1.35, -1.65], 'paintDark', { r: 0.05 });
  for (const s of S) R.lamp(C, [s * 0.5, 1.5, -1.81], { r: 0.06, lens: 'lensR', rot: [0, 180, 0] });
  R.box(C, [1.0, 0.4, 0.3], [0, 0.95, -1.95], 'dark', { r: 0.03 });
  for (const s of S) R.box(C, [0.1, 0.16, 0.2], [s * 0.8, 1.5, 1.1], 'dark', { r: 0.02 });

  // ── 拳头：藏在推铲后，合体时沿滑轨伸出 ──
  const F = R.part('fist', C, [0, 0.65, 1.85], [{ t: [0.52, 0.74], p: [0, 0, 1.3], e: 'back' }]);
  R.box(F, [0.66, 0.56, 0.5], [0, 0.65, 1.2], 'dark', { r: 0.05 });
  R.box(F, [1.24, 1.1, 1.1], [0, 0.65, 1.85], 'purple', { r: 0.1 });
  for (let i = 0; i < 4; i++) {
    const y = 0.65 + (i - 1.5) * 0.27;
    R.box(F, [0.1, 0.22, 0.34], [-0.66, y, 1.95], 'purple', { r: 0.04 });
    R.box(F, [0.55, 0.22, 0.06], [-0.3, y, 2.42], 'purple', { r: 0.02 });
  }
  R.box(F, [0.36, 0.24, 0.5], [-0.42, 0.06, 1.75], 'purple', { r: 0.06 });

  // ── 推铲：弧形铲板，绕推臂根部翻起 90° 后沿滑轨前推 ──
  const Bl = R.part('blade', C, [0, 0.55, 0.3], [{ t: [0.25, 0.55], r: [-90, 0, 0] }, { t: [0.55, 0.72], p: [0, 0, 0.9] }]);
  const N = 12, zf = t => 2.72 - 0.16 * Math.sin(Math.PI * t), yb = t => 0.05 + 1.4 * t;
  const sh = new THREE.Shape();
  for (let i = 0; i <= N; i++) { const t = i / N; i ? sh.lineTo(-(zf(t) - 0.1), yb(t)) : sh.moveTo(-(zf(t) - 0.1), yb(t)); }
  sh.lineTo(-2.84, 1.49); sh.lineTo(-2.86, 1.4);
  for (let i = N; i >= 0; i--) { const t = i / N; sh.lineTo(-zf(t), yb(t)); }
  R.extrude(Bl, sh, 2.9, 'x', [0, 0, 0], 'paint', { bevel: 0.015 });
  R.box(Bl, [2.92, 0.12, 0.12], [0, 0.08, 2.68], 'steel', { r: 0.01 });
  for (const s of S) R.box(Bl, [0.12, 0.3, 0.14], [s * 1.42, 0.2, 2.68], 'steel', { r: 0.02 });
  for (const t of [0.2, 0.5, 0.8]) R.box(Bl, [2.7, 0.1, 0.12], [0, yb(t), zf(t) - 0.15], 'paintDark', { r: 0.02 });
  for (const s of S) {
    R.beam(Bl, [s * 1.35, 0.55, 0.3], [s * 1.35, 0.6, 2.45], [0.14, 0.22], 'paintDark');
    R.cyl(Bl, 0.1, 0.18, [s * 1.35, 0.55, 0.3], 'chrome', { axis: 'x' });
    R.box(Bl, [0.12, 0.18, 0.18], [s * 0.85, 1.1, 2.42], 'dark', { r: 0.02 });
    R.piston(C, [s * 0.8, 1.5, 1.1], Bl, [s * 0.85, 1.1, 2.5], { r: 0.07, k: 0.65 });
  }

  // ── 松土器：车尾折起，合体后成肩部尖角 ──
  const Rp = R.part('ripper', C, [0, 0.95, -1.9], [{ t: [0.3, 0.55], r: [80, 0, 0] }]);
  R.beam(Rp, [0, 0.95, -1.9], [0, 0.85, -2.55], [0.8, 0.22], 'dark');
  R.beam(Rp, [0, 0.95, -2.55], [0, 0.12, -2.7], [0.16, 0.26], 'paintDark');
  R.beam(Rp, [0, 0.3, -2.67], [0, 0.03, -2.6], [0.1, 0.12], 'chrome');
  R.cyl(Rp, 0.08, 0.9, [0, 0.95, -1.9], 'chrome', { axis: 'x' });

  R.bake();
  return {
    rig: R,
    // 整车竖立在大力神左侧（世界 +X）：车辆 X→-Z，Y→X（车顶朝外），Z→-Y（车头朝下）
    dock: { p: [3.55, 8.0, -0.2], q: basis([0, 0, -1], [1, 0, 0], [0, -1, 0]) },
    pre: [8.5, 8.0, -0.2],
  };
}
