// 清扫机 Scavenger —— 履带挖掘机 → 右臂（整车竖立：履带底板贴向躯干，车尾朝下伸出紫色拳头；上车前滑，动臂压平、斗杆前翻上举，铲斗立在右肩）
import * as THREE from 'three';
import { Rig, emblemBadge, basis, DEG } from '../kit.js';

/** (z, y) 轮廓 → Shape（配合 extrude 'x'：形状 x 对应 -Z） */
const profile = pts => { const s = new THREE.Shape(); pts.forEach(([z, y], i) => (i ? s.lineTo(-z, y) : s.moveTo(-z, y))); return s; };

export function buildScavenger(M) {
  const R = new Rig('scavenger', M);
  const S = [-1, 1];

  // ── 下车（根）：履带、车架、回转支承、尾部滑轨 ──
  const C = R.part('chassis', null, [0, 0, 0]);
  for (const s of S) R.track(C, [s * 0.95, 0.42, 0], { L: 3.3, R: 0.42, w: 0.6 });
  R.box(C, [1.3, 0.4, 2.6], [0, 0.62, 0], 'dark', { r: 0.05 });
  for (const z of [-0.8, 0.8]) R.box(C, [1.9, 0.2, 0.6], [0, 0.6, z], 'dark', { r: 0.03 });
  R.cyl(C, 0.72, 0.16, [0, 0.9, 0], 'dark', { seg: 32 });
  R.cyl(C, 0.78, 0.04, [0, 0.84, 0], 'steel', { seg: 32 });
  R.box(C, [0.5, 0.36, 1.1], [0, 0.65, -1.7], 'dark', { r: 0.03 });

  // ── 拳头：藏在车尾，合体时沿滑轨伸出 ──
  const F = R.part('fist', C, [0, 0.65, -2.2], [{ t: [0.55, 0.75], p: [0, 0, -0.75], e: 'back' }]);
  R.box(F, [0.66, 0.56, 0.5], [0, 0.65, -1.9], 'dark', { r: 0.05 });
  R.box(F, [1.25, 1.1, 1.1], [0, 0.65, -2.5], 'purple', { r: 0.1 });
  for (let i = 0; i < 4; i++) {
    const y = 0.65 + (i - 1.5) * 0.27;
    R.box(F, [0.1, 0.22, 0.34], [-0.66, y, -2.72], 'purple', { r: 0.04 });
    R.box(F, [0.55, 0.22, 0.06], [-0.3, y, -3.07], 'purple', { r: 0.02 });
  }
  R.box(F, [0.36, 0.24, 0.5], [-0.42, 0.06, -2.35], 'purple', { r: 0.06 });

  // ── 紫色步枪：握把插进拳心，枪身贴在拳外侧（车顶一侧），枪口朝下、向外偏 15°。
  //    局部坐标：+X 指向枪口，+Y 为枪背（朝外），Z 为枪身宽度方向。拳头伸出后从拳心弹出，前管随后伸长 ──
  const gc = Math.cos(15 * DEG), gs = Math.sin(15 * DEG);
  const G = R.part('gun', F, [-0.25, 1.42, -2.5], [
    { t: [-1, -0.5], s: 0.001, p: [0.25, -0.77, 0] },          // 收在拳心
    { t: [0.76, 0.86], s: 1, e: 'back' },
    { t: [0.76, 0.84], p: [0, 0, 0], e: 'out' },
  ], { frame: true, q0: basis([0, gs, -gc], [0, gc, gs], [1, 0, 0]) });
  const gunBody = new THREE.Shape([[-0.86, 0], [0.74, 0], [0.74, 0.26], [0.5, 0.26], [0.38, 0.34], [-0.7, 0.34], [-0.86, 0.2]].map(([x, y]) => new THREE.Vector2(x, y)));
  R.extrude(G, gunBody, 0.24, 'z', [0, 0, 0], 'purple', { bevel: 0.015 });
  for (const z of [-0.14, 0.14]) {
    R.box(G, [0.95, 0.1, 0.02], [-0.18, 0.18, z], 'dark', { r: 0 });                    // 侧面嵌板
    R.box(G, [0.3, 0.06, 0.02], [0.52, 0.12, z], 'dark', { r: 0 });
  }
  for (let i = 0; i < 4; i++) R.box(G, [0.05, 0.02, 0.16], [-0.5 + i * 0.12, 0.355, 0], 'black', { r: 0 });   // 顶部散热槽
  R.box(G, [0.28, 0.1, 0.1], [0.1, 0.4, 0], 'purple', { r: 0.02 });                        // 照门
  R.box(G, [0.2, 0.62, 0.17], [-0.12, -0.28, 0], 'purple', { r: 0.04, rot: [0, 0, -12] }); // 握把（大半没入拳心）
  R.box(G, [0.22, 0.04, 0.08], [0.12, -0.15, 0], 'dark', { r: 0.01 });                     // 扳机护圈
  R.box(G, [0.04, 0.15, 0.08], [0.22, -0.08, 0], 'dark', { r: 0.01 });
  R.cyl(G, 0.11, 1.2, [1.3, 0.15, 0], 'purple', { axis: 'x' });                            // 枪管外套
  for (const x of [1.0, 1.1, 1.2]) R.cyl(G, 0.125, 0.045, [x, 0.15, 0], 'dark', { axis: 'x' });
  R.cyl(G, 0.14, 0.12, [1.85, 0.15, 0], 'purple', { axis: 'x' });
  R.box(G, [0.7, 0.1, 0.035], [1.35, 0.3, 0], 'purple', { r: 0.01 });                      // 枪管背鳍
  R.cyl(G, 0.035, 0.14, [1.5, -0.01, 0], 'dark');                                         // 挂销
  // 前管：收起时整段藏在机匣与外套里，只露出喇叭形枪口
  const G2 = R.part('gunFore', G, [0, 0, 0], [{ t: [0.86, 0.97], p: [1.45, 0, 0], e: 'back' }]);
  R.cyl(G2, 0.075, 1.75, [1.0, 0.15, 0], 'purple', { axis: 'x' });
  for (const x of [0.95, 1.35]) R.cyl(G2, 0.09, 0.05, [x, 0.15, 0], 'dark', { axis: 'x' });
  R.cyl(G2, 0.15, 0.2, [1.98, 0.15, 0], 'purple', { rb: 0.09, axis: 'x' });
  R.cyl(G2, 0.155, 0.03, [2.07, 0.15, 0], 'dark', { axis: 'x' });
  R.cyl(G2, 0.1, 0.012, [2.085, 0.15, 0], 'black', { axis: 'x' });
  R.box(G2, [0.14, 0.1, 0.03], [1.96, 0.33, 0], 'purple', { r: 0.01 });                    // 准星

  // ── 上车：平台、发动机罩、配重、驾驶室；合体时前滑 ──
  const H = R.part('house', C, [0, 1.0, 0], [{ t: [0.18, 0.4], p: [0, 0, 0.8] }]);
  R.box(H, [2.3, 0.22, 2.9], [0, 1.11, -0.2], 'paint', { r: 0.04 });
  R.box(H, [2.2, 0.06, 2.8], [0, 0.98, -0.2], 'dark', { r: 0.01 });
  R.box(H, [2.2, 0.6, 1.3], [0, 1.52, -0.8], 'paint', { r: 0.06 });
  for (let i = 0; i < 5; i++) R.box(H, [1.2, 0.03, 0.06], [-0.2, 1.835, -1.2 + i * 0.2], 'black', { r: 0 });
  for (const s of S) R.extrude(H, emblemBadge(0.42), 0.02, 'x', [s * 1.11, 1.52, -0.8], 'purple', { bevel: 0.002 });
  R.box(H, [2.3, 0.72, 0.42], [0, 1.5, -1.5], 'paintDark', { r: 0.08 });
  R.box(H, [2.0, 0.1, 0.03], [0, 1.5, -1.72], 'hazard', { r: 0 });
  for (const s of S) R.lamp(H, [s * 0.85, 1.72, -1.73], { r: 0.06, lens: 'lensR', rot: [0, 180, 0] });
  R.box(H, [0.9, 1.3, 1.05], [0.62, 1.87, 0.65], 'paint', { r: 0.08 });
  R.box(H, [0.76, 0.85, 0.04], [0.62, 2.0, 1.18], 'glass', { r: 0 });
  for (const x of [0.165, 1.075]) R.box(H, [0.04, 0.7, 0.8], [x, 2.05, 0.65], 'glass', { r: 0 });
  R.box(H, [0.96, 0.06, 1.1], [0.62, 2.55, 0.65], 'dark', { r: 0.02 });
  R.lamp(H, [0.62, 2.38, 1.21], { r: 0.07, cone: true, len: 6 });
  R.cyl(H, 0.06, 0.08, [0.62, 2.62, 0.4], 'lensA');
  R.box(H, [0.6, 0.42, 1.0], [-0.8, 1.43, 0.6], 'paint', { r: 0.04 });
  R.cyl(H, 0.06, 0.55, [-0.75, 2.05, -0.95], 'chrome');
  R.cyl(H, 0.075, 0.05, [-0.75, 2.34, -0.95], 'dark');
  for (const s of S) R.box(H, [0.08, 0.55, 0.5], [-0.25 + s * 0.22, 1.42, 1.0], 'dark', { r: 0.02 });
  for (const x of [-0.5, 0]) R.box(H, [0.12, 0.18, 0.26], [x, 1.1, 1.36], 'dark', { r: 0.02 });

  // ── 动臂：绕根部下压 45°，指向车头（合体后朝上）──
  const B = R.part('boom', H, [-0.25, 1.45, 1.0], [{ t: [0.4, 0.62], r: [45, 0, 0] }]);
  R.beam(B, [-0.25, 1.45, 1.0], [-0.25, 2.85, 2.5], [0.34, 0.42], 'paint');
  R.beam(B, [-0.25, 2.85, 2.5], [-0.25, 3.05, 3.3], [0.3, 0.4], 'paint');
  R.box(B, [0.36, 0.4, 0.44], [-0.25, 2.85, 2.5], 'paint', { r: 0.08 });
  R.cyl(B, 0.09, 0.56, [-0.25, 1.45, 1.0], 'chrome', { axis: 'x' });
  R.box(B, [0.64, 0.14, 0.22], [-0.25, 2.1, 2.05], 'dark', { r: 0.02 });
  R.cyl(B, 0.045, 0.7, [-0.25, 2.05, 2.05], 'chrome', { axis: 'x' });
  R.box(B, [0.2, 0.3, 0.26], [-0.25, 2.88, 2.1], 'dark', { r: 0.02 });
  for (const s of S) R.beam(B, [-0.25 + s * 0.19, 1.7, 1.3], [-0.25 + s * 0.19, 2.95, 2.9], [0.03, 0.03], 'black');   // 液压管
  for (const x of [-0.5, 0]) R.piston(H, [x, 1.1, 1.45], B, [x, 2.05, 2.05], { r: 0.075, k: 0.6 });

  // ── 斗杆：先前翻，再上举到头顶外侧（分两段，避免穿过动臂）──
  const K = R.part('stick', B, [-0.25, 3.05, 3.3], [{ t: [0.44, 0.58], r: [-90, 0, 0] }, { t: [0.58, 0.72], r: [-179, 0, 0] }]);
  R.beam(K, [-0.25, 3.05, 3.3], [-0.25, 1.0, 4.1], [0.28, 0.36], 'paint');
  R.beam(K, [-0.25, 3.05, 3.3], [-0.25, 3.4, 3.15], [0.24, 0.3], 'paintDark');
  R.cyl(K, 0.08, 0.5, [-0.25, 3.05, 3.3], 'chrome', { axis: 'x' });
  R.box(K, [0.2, 0.2, 0.26], [-0.25, 2.84, 3.56], 'dark', { r: 0.02 });
  R.piston(B, [-0.25, 3.0, 2.1], K, [-0.25, 3.4, 3.15], { r: 0.075, k: 0.75 });

  // ── 铲斗：弧形斗壳 + 侧板 + 斗齿，合体时内收 ──
  const Bk = R.part('bucket', K, [-0.25, 1.0, 4.1], [{ t: [0.5, 0.7], r: [60, 0, 0] }]);
  R.extrude(Bk, profile([[4.1, 1.0], [4.5, 0.95], [4.72, 0.62], [4.66, 0.25], [4.4, 0.04], [3.85, 0.0], [3.9, 0.12], [4.15, 0.3], [4.2, 0.6], [4.05, 0.85]]), 0.8, 'x', [-0.25, 0, 0], 'paint', { bevel: 0.01 });
  for (const s of S) R.extrude(Bk, profile([[4.1, 1.0], [4.5, 0.95], [4.72, 0.62], [4.66, 0.25], [4.4, 0.04], [3.85, 0.0], [4.0, 0.55]]), 0.05, 'x', [-0.25 + s * 0.42, 0, 0], 'paintDark', { bevel: 0.008 });
  for (let i = 0; i < 5; i++) { const x = -0.25 + (i - 2) * 0.17; R.beam(Bk, [x, 0.1, 3.95], [x, 0.02, 3.72], [0.07, 0.06], 'chrome'); }
  for (const s of S) R.box(Bk, [0.08, 0.3, 0.36], [-0.25 + s * 0.2, 0.98, 4.2], 'dark', { r: 0.02 });
  R.cyl(Bk, 0.07, 0.5, [-0.25, 1.0, 4.1], 'chrome', { axis: 'x' });
  R.box(Bk, [0.2, 0.16, 0.2], [-0.25, 1.05, 4.35], 'dark', { r: 0.02 });
  R.piston(K, [-0.25, 2.84, 3.66], Bk, [-0.25, 1.1, 4.35], { r: 0.065, k: 0.6 });

  R.bake();
  return {
    rig: R,
    // 整车竖立在大力神右侧（世界 -X）：车辆 X→-Z，Y→-X（车顶朝外），Z→Y（车头朝上）
    dock: { p: [-3.55, 8.0, -0.2], q: basis([0, 0, -1], [-1, 0, 0], [0, 1, 0]) },
    pre: [-8.5, 8.0, -0.2],
  };
}
