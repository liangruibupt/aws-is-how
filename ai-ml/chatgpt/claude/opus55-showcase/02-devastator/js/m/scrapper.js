// 铲土机 Scrapper —— 轮式装载机 → 右腿（车顶朝后立起，铲斗翻转成脚）
import * as THREE from 'three';
import { Rig, emblemBadge, basis } from '../kit.js';

export function buildScrapper(M) {
  const R = new Rig('scrapper', M);
  const S = [-1, 1];

  // ── 后车架（根）：发动机罩、配重、后轮 ──
  const C = R.part('chassis', null, [0, 0, 0]);
  R.box(C, [1.5, 0.72, 2.45], [0, 0.94, -1.72], 'steel', { r: 0.06 });
  R.box(C, [1.38, 0.62, 2.25], [0, 1.6, -1.85], 'paint', { r: 0.1 });
  R.box(C, [0.9, 0.08, 1.9], [0, 1.94, -1.9], 'paint', { r: 0.03 });
  for (const s of S) for (let i = 0; i < 4; i++) R.box(C, [0.04, 0.05, 0.9], [s * 0.695, 1.42 + i * 0.1, -2.3], 'black', { r: 0.01 });
  R.box(C, [1.2, 0.7, 0.06], [0, 1.35, -2.99], 'black', { r: 0.01 });
  for (let i = 0; i < 6; i++) R.box(C, [1.16, 0.04, 0.05], [0, 1.08 + i * 0.105, -3.02], 'steel', { r: 0.01 });
  R.box(C, [1.72, 0.5, 0.38], [0, 0.78, -2.95], 'paintDark', { r: 0.1 });
  for (const s of S) R.lamp(C, [s * 0.62, 0.86, -3.15], { r: 0.07, lens: 'lensR', rot: [0, 180, 0] });
  R.cyl(C, 0.075, 0.7, [0.42, 2.25, -2.45], 'chrome');
  R.cyl(C, 0.09, 0.06, [0.42, 2.6, -2.45], 'dark');
  R.cyl(C, 0.15, 0.4, [-0.42, 2.1, -1.95], 'dark');
  R.cyl(C, 0.16, 1.6, [0, 0.66, -1.85], 'dark', { axis: 'x' });
  R.box(C, [1.2, 0.08, 2.1], [0, 0.55, -1.75], 'steel', { r: 0.02 });
  for (const s of S) {
    R.box(C, [0.64, 0.08, 1.45], [s * 1.02, 1.36, -1.85], 'paintDark', { r: 0.03 });
    R.box(C, [0.08, 0.3, 1.45], [s * 1.3, 1.24, -1.85], 'paintDark', { r: 0.02 });
    for (let i = 0; i < 3; i++) R.box(C, [0.28, 0.04, 0.2], [s * 0.86, 0.55 + i * 0.3, -0.72], 'steel', { r: 0.01 });
    R.extrude(C, emblemBadge(0.42), 0.02, 'x', [s * 0.77, 1.02, -1.55], 'purple', { bevel: 0.002 });
  }
  for (const s of S) R.wheel(C, [s * 1.02, 0.66, -1.85], 0.66, 0.52);

  // 髋关节（藏在机舱里，腿态时从尾部伸出）
  const hip = R.part('hip', C, [0, 1.1, -2.4], [{ t: [0.6, 0.78], p: [0, 0, -0.55] }]);
  R.box(hip, [1.0, 0.9, 1.0], [0, 1.1, -2.4], 'steel', { r: 0.08 });
  R.cyl(hip, 0.34, 1.26, [0, 1.1, -2.8], 'chrome', { axis: 'x' });

  // ── 驾驶室 ──
  const cab = R.part('cab', C, [0, 1.9, -0.8]);
  R.box(cab, [1.3, 0.1, 1.3], [0, 1.92, -0.8], 'dark');
  R.box(cab, [1.26, 0.28, 1.26], [0, 2.07, -0.8], 'paint', { r: 0.03 });
  for (const x of [-0.6, 0.6]) for (const z of [-0.2, -1.4]) R.box(cab, [0.09, 0.95, 0.09], [x, 2.42, z], 'paint', { r: 0.02 });
  R.box(cab, [1.46, 0.12, 1.46], [0, 2.94, -0.8], 'paint', { r: 0.05 });
  R.box(cab, [1.12, 0.66, 0.03], [0, 2.54, -0.19], 'glass', { r: 0 });
  R.box(cab, [1.12, 0.66, 0.03], [0, 2.54, -1.41], 'glass', { r: 0 });
  for (const s of S) R.box(cab, [0.03, 0.66, 1.12], [s * 0.61, 2.54, -0.8], 'glass', { r: 0 });
  R.box(cab, [0.5, 0.42, 0.42], [0, 2.3, -0.95], 'black');
  for (const s of S) R.lamp(cab, [s * 0.5, 2.88, -0.1], { r: 0.075, cone: true, len: 6 });
  R.cyl(cab, 0.09, 0.14, [0.45, 3.07, -1.25], 'lensA');

  // ── 铰接（膝）──
  const hitch = R.part('hitch', C, [0, 0.95, -0.1]);
  R.box(hitch, [0.9, 0.72, 0.62], [0, 0.95, -0.1], 'purple', { r: 0.06 });
  R.cyl(hitch, 0.12, 0.86, [0, 0.95, -0.1], 'chrome');
  const knee = R.part('knee', C, [0, 0.75, -0.1], [{ t: [0.62, 0.8], p: [0, -0.46, 0], e: 'back' }]);
  R.box(knee, [1.12, 0.26, 0.86], [0, 0.72, -0.1], 'purple', { r: 0.08 });
  R.box(knee, [0.7, 0.1, 0.5], [0, 0.57, -0.1], 'purple', { r: 0.04 });

  // ── 前车架：前轮、大灯、动臂塔 ──
  const F = R.part('front', C, [0, 0.95, 0.15]);
  R.box(F, [1.22, 0.62, 1.55], [0, 0.92, 0.9], 'paintDark', { r: 0.06 });
  R.box(F, [1.0, 0.3, 1.2], [0, 1.36, 0.85], 'paint', { r: 0.06 });
  R.box(F, [1.16, 0.1, 1.42], [0, 0.57, 0.9], 'paint', { r: 0.03 });
  R.cyl(F, 0.16, 1.6, [0, 0.66, 0.95], 'dark', { axis: 'x' });
  for (const s of S) {
    R.box(F, [0.64, 0.08, 1.2], [s * 1.02, 1.38, 0.95], 'paint', { r: 0.03 });
    R.box(F, [0.08, 0.28, 1.2], [s * 1.3, 1.27, 0.95], 'paint', { r: 0.02 });
    R.box(F, [0.18, 0.75, 0.4], [s * 0.62, 1.45, 0.25], 'dark', { r: 0.03 });
    R.lamp(F, [s * 0.42, 1.36, 1.47], { r: 0.1, cone: true, len: 8 });
    R.wheel(F, [s * 1.02, 0.66, 0.95], 0.66, 0.52);
  }

  // ── 动臂（紫，腿态成脚踝）──
  const A = R.part('arms', F, [0, 1.45, 0.25], [{ t: [0.5, 0.74], r: [-21, 0, 0] }]);
  for (const s of S) {
    R.beam(A, [s * 0.62, 1.45, 0.25], [s * 0.62, 0.72, 2.25], [0.2, 0.36], 'purple', { r: 0.05 });
    R.cyl(A, 0.11, 0.3, [s * 0.62, 1.45, 0.25], 'chrome', { axis: 'x' });
    R.cyl(A, 0.1, 0.28, [s * 0.62, 0.72, 2.25], 'chrome', { axis: 'x' });
  }
  R.cyl(A, 0.09, 1.26, [0, 1.12, 1.25], 'dark', { axis: 'x' });
  R.beam(A, [0, 1.16, 1.2], [0, 1.72, 1.05], [0.16, 0.22], 'purple', { r: 0.04 });

  // ── 铲斗（脚）──
  const B = R.part('bucket', A, [0, 0.72, 2.25], [{ t: [0.24, 0.56], r: [111, 0, 0] }]);
  R.box(B, [2.46, 1.15, 0.1], [0, 0.68, 2.2], 'paint', { r: 0.03 });
  R.box(B, [2.46, 0.1, 1.46], [0, 0.13, 2.9], 'paint', { r: 0.03 });
  const side = new THREE.Shape([[2.15, 0.08], [3.64, 0.08], [3.64, 0.62], [3.25, 1.12], [2.15, 1.26]].map(([z, y]) => new THREE.Vector2(-z, y)));
  for (const s of S) R.extrude(B, side, 0.06, 'x', [s * 1.2, 0, 0], 'paint', { bevel: 0.015 });
  R.box(B, [2.3, 0.04, 1.32], [0, 0.2, 2.93], 'dark', { r: 0 });
  R.box(B, [2.3, 1.0, 0.04], [0, 0.72, 2.27], 'dark', { r: 0 });
  R.box(B, [2.46, 0.12, 0.36], [0, 1.26, 2.32], 'paint', { r: 0.03 });
  R.box(B, [2.5, 0.07, 0.16], [0, 0.11, 3.66], 'steel', { r: 0.02 });
  for (let i = 0; i < 7; i++) R.box(B, [0.12, 0.07, 0.26], [-1.08 + i * 0.36, 0.11, 3.8], 'chrome', { r: 0.02 });
  for (const s of S) {
    R.box(B, [0.12, 0.5, 0.35], [s * 0.62, 0.85, 2.05], 'dark', { r: 0.02 });
    R.box(B, [0.1, 1.0, 0.08], [s * 0.4, 0.68, 2.12], 'paintDark', { r: 0.02 });
  }

  // ── 液压缸 ──
  for (const s of S) R.piston(F, [s * 0.62, 0.8, 0.55], A, [s * 0.62, 1.12, 1.35], { r: 0.08 });
  R.piston(A, [0, 1.72, 1.05], B, [0, 1.05, 2.18], { r: 0.07 });

  R.bake();
  return {
    rig: R,
    // 车顶朝后、车头朝下：车辆 X→-X，Y→-Z，Z→-Y
    dock: { p: [-1.65, 2.94, 1.1], q: basis([-1, 0, 0], [0, 0, -1], [0, -1, 0]) },
    pre: [-3.2, 6.6, 3.0],
  };
}
