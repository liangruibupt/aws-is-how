// 拖斗 Long Haul —— 自卸卡车 → 腰部（整车横置；先举斗亮相、尾门自然下垂，再落斗，紫色护裆滑下）
import { Rig, emblemBadge, basis } from '../kit.js';

export function buildLonghaul(M) {
  const R = new Rig('longhaul', M);
  const S = [-1, 1];

  // ── 底盘（根）：大梁、车桥、油箱、工具箱 ──
  const C = R.part('chassis', null, [0, 0, 0]);
  for (const s of S) R.box(C, [0.2, 0.3, 5.9], [s * 0.45, 0.72, -0.1], 'dark', { r: 0.02 });
  for (const z of [-2.8, -1.8, -0.6, 0.6, 1.6]) R.box(C, [0.9, 0.12, 0.14], [0, 0.72, z], 'dark', { r: 0.01 });
  for (const z of [2.2, -1.2, -2.4]) {
    R.cyl(C, 0.1, 1.7, [0, 0.58, z], 'dark', { axis: 'x' });
    if (z < 0) R.box(C, [0.46, 0.24, 0.36], [0, 0.58, z], 'dark', { r: 0.05 });
  }
  R.box(C, [2.2, 0.18, 0.14], [0, 0.62, -3.1], 'hazard', { r: 0.02 });
  for (const s of S) {
    R.lamp(C, [s * 0.85, 0.62, -3.18], { r: 0.07, lens: 'lensR', rot: [0, 180, 0] });
    R.box(C, [0.2, 0.3, 0.2], [s * 0.45, 0.95, -2.95], 'dark', { r: 0.03 });           // 翻斗铰座
    for (const z of [2.2, -1.2, -2.4]) R.wheel(C, [s * 1.0, 0.58, z], 0.58, 0.5);
  }
  R.cyl(C, 0.07, 1.1, [0, 1.0, -2.95], 'chrome', { axis: 'x' });
  R.cyl(C, 0.24, 0.85, [-0.86, 0.66, 0.85], 'steel', { axis: 'z', seg: 20 });
  for (const z of [0.6, 1.1]) R.box(C, [0.52, 0.05, 0.05], [-0.86, 0.9, z], 'dark', { r: 0.01 });
  R.box(C, [0.4, 0.42, 0.62], [0.88, 0.72, 0.92], 'dark', { r: 0.04 });
  R.box(C, [0.7, 0.14, 0.3], [0.82, 0.96, 0], 'dark', { r: 0.02 });                   // 护裆滑轨座
  R.box(C, [0.36, 0.14, 0.36], [0, 0.47, 0.9], 'dark', { r: 0.03 });

  // ── 驾驶室（平头）──
  R.box(C, [1.44, 0.6, 1.36], [0, 1.15, 2.25], 'paintDark', { r: 0.05 });
  R.box(C, [2.24, 0.92, 1.4], [0, 1.91, 2.25], 'paint', { r: 0.1 });
  R.box(C, [1.9, 0.5, 0.04], [0, 2.02, 2.96], 'glass', { r: 0 });
  R.box(C, [1.2, 0.38, 0.04], [0, 1.2, 2.94], 'black', { r: 0 });
  for (const y of [1.08, 1.2, 1.32]) R.box(C, [1.16, 0.03, 0.03], [0, y, 2.97], 'chrome', { r: 0 });
  R.box(C, [2.36, 0.26, 0.3], [0, 0.78, 3.0], 'steel', { r: 0.04 });
  R.box(C, [2.0, 0.06, 0.3], [0, 2.4, 2.88], 'dark', { r: 0.02 });
  for (const x of [-0.55, 0, 0.55]) R.cyl(C, 0.06, 0.08, [x, 2.47, 2.7], 'lensA');
  for (const s of S) {
    R.lamp(C, [s * 0.85, 0.8, 3.16], { r: 0.09, cone: true, len: 8 });
    R.box(C, [0.04, 0.42, 0.62], [s * 1.125, 2.03, 2.5], 'glass', { r: 0 });
    R.box(C, [0.56, 0.08, 1.3], [s * 1.0, 1.26, 2.2], 'paintDark', { r: 0.02 });
    R.beam(C, [s * 1.1, 2.1, 2.8], [s * 1.34, 2.0, 2.9], [0.04, 0.04], 'dark');
    R.box(C, [0.05, 0.34, 0.18], [s * 1.37, 1.88, 2.9], 'black', { r: 0.02 });
    R.extrude(C, emblemBadge(0.36), 0.02, 'x', [s * 1.125, 1.64, 2.12], 'purple', { bevel: 0.002 });
  }
  R.cyl(C, 0.07, 1.4, [-1.24, 2.15, 1.48], 'chrome');
  R.cyl(C, 0.085, 0.05, [-1.24, 2.86, 1.48], 'dark');

  // ── 翻斗：绕后铰点举起 35°，再落回 ──
  const B = R.part('bed', C, [0, 1.0, -2.95], [{ t: [0.06, 0.3], r: [-35, 0, 0] }, { t: [0.36, 0.56], r: [0, 0, 0] }]);
  for (const s of S) R.box(B, [0.16, 0.32, 4.2], [s * 0.45, 1.06, -0.85], 'dark', { r: 0.02 });
  R.box(B, [2.36, 0.12, 4.35], [0, 1.28, -0.8], 'paint', { r: 0.03 });
  for (const z of [-2.9, -1.8, -0.6, 0.5, 1.3]) R.box(B, [2.3, 0.1, 0.1], [0, 1.17, z], 'paintDark', { r: 0.01 });
  for (const s of S) {
    R.box(B, [0.1, 1.2, 4.35], [s * 1.2, 1.9, -0.8], 'paint', { r: 0.03 });
    R.box(B, [0.2, 0.12, 4.4], [s * 1.2, 2.5, -0.8], 'paintDark', { r: 0.03 });
    R.box(B, [0.06, 0.1, 4.3], [s * 1.27, 1.42, -0.8], 'paintDark', { r: 0.02 });
    for (const z of [-2.5, -1.6, 0.8]) R.box(B, [0.07, 1.1, 0.12], [s * 1.28, 1.88, z], 'paintDark', { r: 0.02 });
  }
  R.extrude(B, emblemBadge(0.72), 0.03, 'x', [1.27, 1.9, 0], 'purple', { bevel: 0.003 });
  R.box(B, [2.36, 1.28, 0.1], [0, 1.94, 1.37], 'paint', { r: 0.03 });
  R.box(B, [2.3, 0.1, 1.5], [0, 2.58, 2.1], 'paint', { r: 0.03 });
  R.box(B, [2.3, 0.08, 0.08], [0, 2.52, 2.82], 'paintDark', { r: 0.01 });
  for (const s of S) R.beam(B, [s * 1.1, 2.1, 1.42], [s * 1.1, 2.53, 1.9], [0.06, 0.08], 'paintDark');

  // 尾门：顶部铰接，举斗时保持竖直下垂
  const G = R.part('gate', B, [0, 2.45, -3.02], [{ t: [0.06, 0.3], r: [35, 0, 0] }, { t: [0.36, 0.56], r: [0, 0, 0] }]);
  R.box(G, [2.36, 1.15, 0.1], [0, 1.9, -3.02], 'paint', { r: 0.03 });
  for (const y of [1.6, 2.2]) R.box(G, [2.3, 0.08, 0.06], [0, y, -3.09], 'paintDark', { r: 0.01 });
  R.cyl(G, 0.05, 2.4, [0, 2.45, -3.02], 'chrome', { axis: 'x' });

  // 多级举升缸
  R.piston(C, [0, 0.5, 0.9], B, [0, 1.22, 0.9], { r: 0.13, n: 5, k: 0.9 });

  // ── 紫色护裆：侧裙板，合体时滑下填在两腿之间 ──
  const P = R.part('groin', C, [1.22, 1.15, 0], [{ t: [0.6, 0.82], p: [0, -0.6, 0], e: 'back' }]);
  R.box(P, [0.12, 0.8, 0.9], [1.22, 0.75, 0], 'purple', { r: 0.04 });
  R.box(P, [0.12, 0.4, 0.56], [1.31, 0.6, 0], 'purple', { r: 0.04 });
  R.box(P, [0.08, 1.2, 0.14], [1.13, 0.95, 0], 'dark', { r: 0.02 });

  R.bake();
  return {
    rig: R,
    // 整车横置，车头朝大力神右侧（世界 -X）：车辆 X→Z，Y→Y，Z→-X
    dock: { p: [0, 6.1, -0.2], q: basis([0, 0, 1], [0, 1, 0], [-1, 0, 0]) },
    pre: [0, 11.2, 2.2],
  };
}
